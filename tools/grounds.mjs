// Run: node tools/grounds.mjs   (ffmpeg; rerun when a project's hero changes)
// The ground of each project's plate on the home page (D86): the dominant colour of its hero render, mixed
// 16% into each scheme's ground, so every plate carries its own light and the text keeps its contrast.
// Writes content/grounds.json: { slug: { light: "#rrggbb", dark: "#rrggbb" } }.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MIX = 0.16;
const BASES = { light: [255, 255, 255], dark: [0x12, 0x13, 0x11] };
const hex = (rgb) => '#' + rgb.map((v) => Math.round(v).toString(16).padStart(2, '0')).join('').toUpperCase();
const out = { $comment: 'Generated by tools/grounds.mjs from each hero render (D86). Do not edit by hand.' };
for (const f of fs.readdirSync(path.join(ROOT, 'content/projects')).sort()) {
  const x = JSON.parse(fs.readFileSync(path.join(ROOT, 'content/projects', f), 'utf8'));
  // 16 x 16 pixels by area averaging, then their mean weighted by chroma squared: the render's dominant hue
  // (a plain mean washes every render to grey, and the plates would all share one ground)
  const px = execFileSync('ffmpeg', ['-v', 'error', '-i', path.join(ROOT, x.hero.src), '-vf', 'scale=16:16:flags=area', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-']);
  if (px.length !== 16 * 16 * 3) throw new Error(`${x.slug}: ffmpeg returned ${px.length} bytes`);
  const sum = [0, 0, 0]; let wt = 0;
  for (let i = 0; i < px.length; i += 3) {
    const c = [px[i], px[i + 1], px[i + 2]]; const w = (Math.max(...c) - Math.min(...c)) ** 2 + 1;
    c.forEach((v, k) => { sum[k] += v * w; }); wt += w;
  }
  const avg = sum.map((v) => v / wt);
  out[x.slug] = Object.fromEntries(Object.entries(BASES).map(([k, b]) => [k, hex(b.map((v, i) => v * (1 - MIX) + avg[i] * MIX))]));
}
fs.writeFileSync(path.join(ROOT, 'content/grounds.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`content/grounds.json: ${Object.keys(out).length - 1} grounds`);
